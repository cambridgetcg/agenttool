function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function jsonl(values) {
  return `${values.map((value) => canonicalJson(value)).join("\n")}\n`;
}

function write(relative, bytes) {
  const path = resolve(stage, relative);
  if (!path.startsWith(`${stage}/`)) throw new Error(`unsafe generated path ${relative}`);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
}

function walk(root, relative = "") {
  const current = resolve(root, relative || ".");
  return readdirSync(current, { withFileTypes: true }).flatMap((entry) => {
    const child = relative ? `${relative}/${entry.name}` : entry.name;
    return entry.isDirectory() ? walk(root, child) : [child];
  });
}

function assertSameTree(left, right) {
  if (!existsSync(right)) throw new Error("generated dataset is absent; run bun run build:hf");
  const leftPaths = walk(left).sort();
  const rightPaths = walk(right).sort();
  if (leftPaths.join("\0") !== rightPaths.join("\0")) {
    throw new Error(`generated path drift\nexpected: ${leftPaths.join(", ")}\nactual: ${rightPaths.join(", ")}`);
  }
  for (const path of leftPaths) {
    const expected = readFileSync(resolve(left, path));
    const actual = readFileSync(resolve(right, path));
    if (!expected.equals(actual)) throw new Error(`generated byte drift: ${path}`);
  }
}

